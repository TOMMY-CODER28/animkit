"""`animkit preview` and `animkit render` — headless ManimGL rendering.

Pipeline position: implementation -> PREVIEW/FINAL RENDER.

ManimGL mechanics used here (verified against ManimGL 1.7.2-dev on this machine):
  - `-w` implies show_in_window=False, i.e. fully headless GPU render.
  - `--video_dir` sets the output directory; the file is always <SceneName>.mp4.
  - `--config_file` merges over defaults; we use it for ffmpeg_bin + crf +
    project-relative asset directories.
"""

from __future__ import annotations

from pathlib import Path

from animkit import env
from animkit.config import Project
from animkit.runs import Run


def _manim_config_yml(project: Project, ffmpeg: Path, crf: int) -> str:
    # Forward slashes avoid YAML escape surprises on Windows.
    base = str(project.root).replace("\\", "/")
    ff = str(ffmpeg).replace("\\", "/")
    return (
        "# Generated by animkit — do not edit; regenerate with `animkit preview/render`.\n"
        "directories:\n"
        f"  base: \"{base}\"\n"
        "file_writer:\n"
        f"  ffmpeg_bin: \"{ff}\"\n"
        f"  crf: {crf}\n"
    )


def render_video(project: Project, mode: str, run: Run, scene_override: str | None = None) -> dict:
    """Render the project scene. mode is 'preview' or 'final'."""
    settings = project.settings(mode)
    scene_name = scene_override or project.scene

    manimgl, gl_source = env.find_manimgl(project.manimgl_setting())
    if not manimgl:
        return {
            "ok": False, "status": "failure", "command": mode,
            "errors": [f"manimgl executable not found (searched config, env, interpreter dir, PATH)"],
            "next_actions": ["Set environment.manimgl in project.json to the manimgl.exe inside your manim venv"],
        }
    ffmpeg, ff_source = env.find_ffmpeg(manimgl)
    if not ffmpeg:
        return {
            "ok": False, "status": "failure", "command": mode,
            "errors": ["No ffmpeg binary found (PATH or imageio-ffmpeg)"],
            "next_actions": ["pip install imageio-ffmpeg into the manim venv"],
        }

    width, height = settings["resolution"]
    run.log_line(f"[animkit] mode={mode} scene={scene_name} {width}x{height}@{settings['fps']}fps crf={settings['crf']}")
    run.log_line(f"[animkit] manimgl={manimgl} ({gl_source})")
    run.log_line(f"[animkit] ffmpeg={ffmpeg} ({ff_source})")

    yml_path = run.dir / "manim_config.yml"
    yml_path.write_text(_manim_config_yml(project, ffmpeg, settings["crf"]), encoding="utf-8")

    video_dir = project.video_dir
    video_dir.mkdir(parents=True, exist_ok=True)
    expected = video_dir / f"{scene_name}.mp4"
    if expected.exists():
        expected.unlink()  # never report a stale file as this run's output

    argv = [
        str(manimgl), "-w",
        "-r", f"{width}x{height}",
        "--fps", str(settings["fps"]),
        "--config_file", str(yml_path),
        "--video_dir", str(video_dir),
    ]
    if settings["background_color"]:
        argv += ["-c", settings["background_color"]]
    argv += [str(project.scene_file), scene_name]

    # TeX support: put latex/dvisvgm on the render subprocess PATH (MiKTeX
    # user install is usually not on PATH). No-op when no TeX is installed.
    run.log_line(f"[animkit] tex: {env.latex_status()}")
    proc_env = env.latex_path_env()

    proc = run.run_subprocess(argv, cwd=project.root, timeout_s=settings["timeout_s"],
                              extra_env=proc_env)

    result = {
        "command": mode,
        "mode": mode,
        "scene": scene_name,
        "details": {
            "resolution": [width, height],
            "fps": settings["fps"],
            "crf": settings["crf"],
            "env": env.env_snapshot(manimgl, gl_source),
            "hashes": project.hashes(),
            "exit_code": proc["exit_code"],
            "wall_s": proc["wall_s"],
        },
    }

    if proc["timed_out"]:
        result.update({
            "ok": False, "status": "timeout",
            "errors": [f"render exceeded timeout of {settings['timeout_s']}s"],
            "next_actions": [
                "Shorten the scene, lower final_fps to 30, or raise timing.render_timeout_s in project.json",
            ],
        })
    elif proc["exit_code"] != 0 or not expected.is_file():
        result.update({
            "ok": False, "status": "failure",
            "errors": [f"manimgl exited with code {proc['exit_code']}"] +
                      ([f"expected output {expected} was not created"] if not expected.is_file() else []),
            "error_excerpt": run.error_excerpt(),
            "next_actions": [
                "Read the log tail above: ManimGL tracebacks usually point at the failing scene line",
                "Fix scene.py, then re-run `animkit preview <project>`",
            ],
        })
    else:
        meta = _probe_video(expected)
        result.update({
            "ok": True, "status": "success",
            "outputs": {"video": str(expected)},
            "details": {**result["details"], "video_meta": meta},
            "next_actions": (
                ["Run `animkit frames <project>` to extract inspection frames"]
                if mode == "preview"
                else ["Run `animkit deliver <project>` to package video + source + reproduction steps"]
            ),
        })
    return result


def _probe_video(path: Path) -> dict | None:
    try:
        import av
        container = av.open(str(path))
        stream = container.streams.video[0]
        meta = {
            "width": stream.codec_context.width,
            "height": stream.codec_context.height,
            "duration_s": round(float(container.duration) / 1e6, 2),
            "fps": round(float(stream.average_rate), 2),
            "size_bytes": path.stat().st_size,
        }
        container.close()
        return meta
    except Exception:
        return {"size_bytes": path.stat().st_size if path.exists() else 0}


def run(args) -> tuple[int, dict]:
    from animkit.config import load_project
    project, errors = load_project(args.project)
    if project is None:
        return 2, {
            "ok": False, "status": "config_error", "command": args.mode,
            "errors": errors,
            "next_actions": ["Fix project.json / missing files, or recreate with `animkit new`"],
        }
    mode = args.mode
    run = Run(project.root, mode)
    try:
        result = render_video(project, mode, run, scene_override=getattr(args, "scene", None))
    finally:
        run.close()
    result.setdefault("project", project.name)
    result.setdefault("outputs", {})
    result = run.write_result(result)
    run.update_index(result)
    return (0 if result["ok"] else (3 if result["status"] == "timeout" else 1)), result
